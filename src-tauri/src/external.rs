        assert!(!is_web_scheme("javascript:alert(1)"));
        assert!(!is_web_scheme("ms-settings:privacy"));
        assert!(!is_web_scheme(""));
        assert!(!is_web_scheme("example.com"), "no scheme, no launch");
        assert!(!is_web_scheme("/C calc.exe"));
