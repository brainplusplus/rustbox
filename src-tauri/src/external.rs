//! Launching apps in an external browser.
//!
//! Two things have to be right here, and both were wrong before:
//!
//! 1. **Which browser family is this?** Firefox and Chromium disagree on almost
//!    every flag. Detection used to be "does the file name contain firefox",
//!    which classified Camoufox — a Firefox build — as Chromium and sent it
//!    `--user-data-dir` and `--fingerprint`, neither of which it understands.
//!
//! 2. **Where does the proxy go?** Chromium takes `--proxy-server` on the
//!    command line. Firefox has no such flag, but it reads `user.js` from the
//!    profile directory at every start, which is a real (and previously unused)
//!    way to apply a per-app proxy instead of documenting it as impossible.
//!
//! The launch itself is built by a pure function so the exact argument list can
//! be unit-tested without spawning a browser.

use crate::config::{App, Engine};
use crate::paths;
use crate::settings::Resolved;
use std::path::{Path, PathBuf};

/// Which command-line dialect a browser speaks.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BrowserFamily {
    /// Chrome, Edge, Brave, Vivaldi, Opera, and stealth builds such as
    /// CloakBrowser. Isolation is `--user-data-dir`, proxy is
    /// `--proxy-server`.
    Chromium,
    /// Firefox and friends. Isolation is `-profile`, proxy has to be written
    /// into the profile's `user.js`.
    Firefox,
    /// Camoufox: a patched Firefox. Same flags as `Firefox`, but its identity
    /// is generated by its own Python wrapper rather than by a CLI seed, so a
    /// seed cannot be honoured by launching the binary directly.
    Camoufox,
}

impl BrowserFamily {
    /// Classify from the executable path.
    ///
    /// Order matters: `camoufox` must be checked before `firefox` because the
    /// name contains neither substring of the other, but a build could be
    /// called `camoufox` and still be a Firefox fork.
    pub fn of(path: &str) -> BrowserFamily {
        let name = Path::new(path)
            .file_stem()
            .map(|s| s.to_string_lossy().to_lowercase())
            .unwrap_or_default();
        if name.contains("camoufox") {
            BrowserFamily::Camoufox
        } else if name.contains("firefox")
            || name.contains("librewolf")
            || name.contains("waterfox")
            || name.contains("tor browser")
            || name.contains("torbrowser")
        {
            BrowserFamily::Firefox
        } else {
            BrowserFamily::Chromium
        }
    }

    fn is_gecko(self) -> bool {
        matches!(self, BrowserFamily::Firefox | BrowserFamily::Camoufox)
    }

    /// Directory name for this family under `external\<app-id>\`.
    ///
    /// Chrome, Edge, Brave and CloakBrowser all get `chromium` so they share one
    /// profile: they speak the same on-disk format, so a login made in one is
    /// already there for the next. Gecko builds get `gecko` because the formats
    /// are incompatible — mixing them in one folder corrupts both.
    pub fn dir_name(self) -> &'static str {
        if self.is_gecko() {
            "gecko"
        } else {
            "chromium"
        }
    }
}

/// Everything needed to start one browser, with no side effects yet.
#[derive(Debug, Default, PartialEq)]
pub struct LaunchPlan {
    pub program: PathBuf,
    pub args: Vec<String>,
    /// Extra environment variables. Camoufox reads its fingerprint from these.
    pub env: Vec<(String, String)>,
    /// Contents for `<profile>/user.js`, which Gecko applies at every start.
    /// `None` means "leave whatever is there alone".
    pub user_js: Option<String>,
    /// Limitations the user should know about, in plain language. Empty when
    /// everything asked for was honoured.
    pub notes: Vec<String>,
}

/// What actually happened, returned to the UI.
///
/// Deliberately redacted: the proxy URI can contain credentials, so only the
/// fact that a proxy was applied is reported, never its value.
#[derive(Debug, Clone, serde::Serialize)]
pub struct LaunchReport {
    /// Executable that was started.
    pub browser: String,
    pub family: &'static str,
    /// Profile directory handed to the browser.
    pub profile: String,
    pub proxy_applied: bool,
    pub seed_applied: bool,
    /// Anything that could not be honoured, so the UI can say why instead of
    /// leaving the user to guess.
    pub notes: Vec<String>,
}

/// Build the launch plan. Pure: no filesystem writes, no process spawn.
///
/// `proxy_uri` is already resolved (an authenticated proxy has been rewritten
/// to point at the local credential-injecting forwarder by then).
pub fn plan(
    app: &App,
    family: BrowserFamily,
    browser_path: &Path,
    profile_dir: &Path,
    proxy_uri: Option<&str>,
) -> LaunchPlan {
    let mut plan = LaunchPlan {
        program: browser_path.to_path_buf(),
        ..Default::default()
    };

    let seed = app
        .fingerprint
        .as_deref()
        .map(str::trim)
        .filter(|s| !s.is_empty());
    let ua = app
        .user_agent
        .as_deref()
        .map(str::trim)
        .filter(|s| !s.is_empty());

    if family.is_gecko() {
        // `-no-remote` stops this launch from being swallowed by an already
        // running instance; `--new-instance` additionally gives it its own
        // process, which is what per-app isolation needs.
        plan.args.push("-no-remote".to_string());
        plan.args.push("--new-instance".to_string());
        plan.args.push("-profile".to_string());
        plan.args.push(profile_dir.display().to_string());
        plan.user_js = Some(gecko_user_js(proxy_uri, ua));

        if seed.is_some() {
            plan.notes.push(match family {
                BrowserFamily::Camoufox => {
                    "Camoufox generates its identity itself; a seed needs its Python wrapper, \
                     so this app keeps a persistent profile but a fresh fingerprint per launch."
                        .to_string()
                }
                _ => "Firefox has no fingerprint seed; only the profile is isolated.".to_string(),
            });
        }
    } else {
        plan.args
            .push(format!("--user-data-dir={}", profile_dir.display()));
        if let Some(uri) = proxy_uri {
            plan.args.push(format!("--proxy-server={uri}"));
        }
        if let Some(seed) = seed {
            // CloakBrowser and similar stealth Chromium builds pin the whole
            // fingerprint from this seed. Plain Chrome ignores unknown switches,
            // so passing it would look like it worked while doing nothing.
            if supports_fingerprint_seed(browser_path) {
                plan.args.push(format!("--fingerprint={seed}"));
            } else {
                plan.notes.push(
                    "This browser ignores fingerprint seeds; use a stealth Chromium build to \
                     pin an identity."
                        .to_string(),
                );
            }
        }
        if let Some(ua) = ua {
            plan.args.push(format!("--user-agent={ua}"));
        }
    }

    // Per-app escape hatch, last so it can override anything above.
    for extra in &app.external_args {
        let extra = extra.trim();
        if !extra.is_empty() {
            plan.args.push(extra.to_string());
        }
    }

    plan
}

/// Whether this binary understands `--fingerprint=<seed>`.
fn supports_fingerprint_seed(browser_path: &Path) -> bool {
    browser_path
        .file_name()
        .map(|f| {
            let n = f.to_string_lossy().to_lowercase();
            n.contains("cloak")
        })
        .unwrap_or(false)
}

/// Write the generated settings into a Gecko profile.
fn write_user_js(profile_dir: &Path, contents: &str) -> Result<(), String> {
    let path = profile_dir.join("user.js");
    std::fs::write(&path, contents).map_err(|e| format!("could not write {}: {e}", path.display()))
}

/// Compose `user.js` for a Gecko profile.
///
/// Written on every launch, including the no-proxy case: `user.js` is replayed
/// over `prefs.js` at startup, so a leftover proxy from a previous launch would
/// otherwise stick forever with no way to clear it from the UI.
fn gecko_user_js(proxy_uri: Option<&str>, user_agent: Option<&str>) -> String {
    let mut out = String::from(
        "// Generated by rustbox on every launch; edits here are overwritten.\n",
    );

    match proxy_uri.and_then(parse_proxy_uri) {
        Some(p) => {
            let is_socks = p.scheme == "socks5" || p.scheme == "socks";
            out.push_str("user_pref(\"network.proxy.type\", 1);\n");
            if is_socks {
                out.push_str(&format!(
                    "user_pref(\"network.proxy.socks\", \"{}\");\n",
                    escape(&p.host)
                ));
                out.push_str(&format!(
                    "user_pref(\"network.proxy.socks_port\", {});\n",
                    p.port
                ));
                out.push_str("user_pref(\"network.proxy.socks_version\", 5);\n");
                // Remote DNS keeps the real hostname off the local resolver,
                // which is the whole point of routing through SOCKS.
                out.push_str("user_pref(\"network.proxy.socks_remote_dns\", true);\n");
            } else {
                for key in ["http", "ssl", "ftp"] {
                    out.push_str(&format!(
                        "user_pref(\"network.proxy.{key}\", \"{}\");\n",
                        escape(&p.host)
                    ));
                    out.push_str(&format!(
                        "user_pref(\"network.proxy.{key}_port\", {});\n",
                        p.port
                    ));
                }
                out.push_str("user_pref(\"network.proxy.share_proxy_settings\", true);\n");
                // Plain-HTTP and HTTPS traffic must not leak around the proxy.
                out.push_str("user_pref(\"network.proxy.no_proxies_on\", \"\");\n");
            }
        }
        None => {
            // 5 = no proxy. Explicit so a previously written proxy is cleared.
            out.push_str("user_pref(\"network.proxy.type\", 5);\n");
        }
    }

    if let Some(ua) = user_agent {
        out.push_str(&format!(
            "user_pref(\"general.useragent.override\", \"{}\");\n",
            escape(ua)
        ));
    }

    out
}

struct ProxyParts {
    scheme: String,
    host: String,
    port: u16,
}

/// Split `scheme://host:port` without pulling in a URL crate.
fn parse_proxy_uri(uri: &str) -> Option<ProxyParts> {
    let (scheme, rest) = uri.split_once("://")?;
    // Tolerate a trailing path, and never let credentials through: an
    // authenticated proxy has already been rewritten to a local forwarder.
    let authority = rest.split('/').next().unwrap_or(rest);
    let (host, port) = authority.rsplit_once(':')?;
    Some(ProxyParts {
        scheme: scheme.to_lowercase(),
        host: host.to_string(),
        port: port.parse().ok()?,
    })
}

/// Escape a value for a double-quoted pref string.
fn escape(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Detect installed browsers on this machine.
#[tauri::command]
pub fn detect_browsers() -> Vec<DetectedBrowser> {
    let mut found: Vec<DetectedBrowser> = Vec::new();
    for (name, rel) in KNOWN_BROWSERS {
        for root in candidate_roots() {
            let candidate = root.join(rel);
            if candidate.exists() {
                let path = candidate.to_string_lossy().into_owned();
                found.push(DetectedBrowser {
                    name: name.to_string(),
                    family: family_label(&path).to_string(),
                    path,
                    source: String::new(),
                });
                break;
            }
        }
    }
    // Anti-detect builds live in user-scoped caches rather than Program Files,
    // so they need their own lookup. Without this the seed/proxy fields would
    // only ever apply to ordinary browsers that cannot use them.
    for b in anti_detect_browsers() {
        if !found.iter().any(|f| f.path == b.path) {
            found.push(b);
        }
    }
    found
}

/// Well-known browser executables we can detect on Windows.
const KNOWN_BROWSERS: &[(&str, &str)] = &[
    ("brave", r"BraveSoftware\Brave-Browser\Application\brave.exe"),
    ("chrome", r"Google\Chrome\Application\chrome.exe"),
    ("edge", r"Microsoft\Edge\Application\msedge.exe"),
    ("firefox", r"Mozilla Firefox\firefox.exe"),
    ("vivaldi", r"Vivaldi\Application\vivaldi.exe"),
    ("opera", r"Opera\opera.exe"),
];

/// Detected installed browser.
#[derive(Debug, Clone, serde::Serialize)]
pub struct DetectedBrowser {
    pub name: String,
    pub path: String,
    /// Which flag dialect this browser speaks, so the UI can word its hints.
    pub family: String,
    /// Where this copy came from, e.g. `DonutBrowser`. Several stealth builds
    /// can be installed side by side under the same `name`, so the picker needs
    /// something to tell them apart. Empty for the ordinary browsers, whose
    /// name is already unique.
    pub source: String,
}

fn candidate_roots() -> Vec<PathBuf> {
    [
        std::env::var("LOCALAPPDATA").ok().map(PathBuf::from),
        std::env::var("ProgramFiles").ok().map(PathBuf::from),
        std::env::var("ProgramFiles(x86)").ok().map(PathBuf::from),
    ]
    .into_iter()
    .flatten()
    .collect()
}

/// Locate stealth browser builds in their user-level caches.
///
/// The layouts are owned by those projects and change between versions, so each
/// candidate is probed for an executable rather than assumed: a missing one
/// costs nothing, and a moved one is picked up by the shallow scan below.
fn anti_detect_browsers() -> Vec<DetectedBrowser> {
    let mut out = Vec::new();
    let local = std::env::var("LOCALAPPDATA").ok().map(PathBuf::from);
    let home = std::env::var("USERPROFILE").ok().map(PathBuf::from);

    if let Some(local) = &local {
        // `camoufox` keeps the binary under its own cache directory. The
        // `.stock.bak` sibling is a pristine copy of the same build, so it is
        // only worth listing when the live cache is gone; offering both would
        // put two identical Camoufox builds in the picker.
        let live = local.join(r"camoufox\camoufox\Cache\camoufox.exe");
        if live.is_file() {
            push_if_exists(&mut out, "camoufox", live);
        } else {
            push_if_exists(
                &mut out,
                "camoufox",
                local.join(r"camoufox\camoufox\Cache.stock.bak\camoufox.exe"),
            );
        }
        // Profile managers vendor their own copies under a version directory.
        for rel in [r"DonutBrowser\binaries\camoufox", r"DonutBrowser\binaries"] {
            for exe in shallow_exes(&local.join(rel), "camoufox", 3) {
                push_if_exists(&mut out, "camoufox", exe);
            }
        }
        for rel in [r"cloakbrowser", r"CloakBrowser"] {
            for exe in shallow_exes(&local.join(rel), "chrome", 3) {
                push_if_exists(&mut out, "cloakbrowser", exe);
            }
        }
    }
    // CloakBrowser's own cache defaults to the home directory.
    if let Some(home) = &home {
        for exe in shallow_exes(&home.join(".cloakbrowser"), "chrome", 3) {
            push_if_exists(&mut out, "cloakbrowser", exe);
        }
    }
    out
}

fn push_if_exists(out: &mut Vec<DetectedBrowser>, name: &str, path: PathBuf) {
    if path.is_file() {
        let path_str = path.to_string_lossy().into_owned();
        if !out.iter().any(|b| b.path == path_str) {
            let source = source_label(&path);
            out.push(DetectedBrowser {
                name: name.to_string(),
                path: path_str.clone(),
                family: family_label(&path_str).to_string(),
                source,
            });
        }
    }
}

/// Short "where did this copy come from" label for the picker.
///
/// Several stealth builds can be installed side by side under the same name, so
/// the picker needs something to tell them apart. The version directory is the
/// wrong answer (it changes on every update and would make a saved choice look
/// stale), so this reports the top-level folder the copy was installed under:
/// `DonutBrowser`, `camoufox`, `.cloakbrowser`. Those names are stable across
/// updates, which is what a user recognises.
fn source_label(path: &Path) -> String {
    let parts: Vec<String> = path
        .components()
        .filter_map(|c| match c {
            std::path::Component::Normal(s) => Some(s.to_string_lossy().into_owned()),
            _ => None,
        })
        .collect();
    let at = |i: usize| parts.get(i).cloned().unwrap_or_default();

    for (i, part) in parts.iter().enumerate() {
        let lower = part.to_lowercase();
        // `...\AppData\Local\<owner>\...` — the usual per-user install root.
        if lower == "local" && i > 0 && parts[i - 1].eq_ignore_ascii_case("appdata") {
            return at(i + 1);
        }
        if lower == "program files" || lower == "program files (x86)" {
            return at(i + 1);
        }
        // `C:\Users\<u>\<owner>\...` — only when the owner is a hidden
        // dot-directory, so a plain `AppData` segment never wins here.
        if lower == "users" {
            let owner = at(i + 2);
            if owner.starts_with('.') {
                return owner;
            }
        }
    }
    // Unknown layout: the folder above the executable is the best available.
    parts
        .len()
        .checked_sub(2)
        .map(at)
        .unwrap_or_default()
}

/// True when `path` is a real `.exe` whose name is exactly `stem`.
///
/// Matching on `file_stem` alone is not enough: these caches keep sibling files
/// that share the stem, so `camoufox.cfg` and `chrome.dll` were being listed as
/// separate browsers next to the real binary. The user only ever launches the
/// `.exe`, so anything else is noise in the picker.
fn is_executable_named(path: &Path, stem: &str) -> bool {
    path.file_name()
        .map(|f| f.to_string_lossy().to_lowercase())
        .and_then(|f| f.strip_suffix(".exe").map(str::to_string))
        .map(|f| f == stem)
        .unwrap_or(false)
}

/// Find `<stem>.exe` under `root` without walking the whole disk. Depth is
/// capped because these caches can contain thousands of files.
fn shallow_exes(root: &Path, stem: &str, depth: usize) -> Vec<PathBuf> {
    fn walk(dir: &Path, stem: &str, depth: usize, out: &mut Vec<PathBuf>) {
        if depth == 0 || out.len() >= 4 {
            return;
        }
        let Ok(entries) = std::fs::read_dir(dir) else { return };
        for entry in entries.flatten() {
            let path = entry.path();
            let Ok(ft) = entry.file_type() else { continue };
            if ft.is_dir() {
                walk(&path, stem, depth - 1, out);
            } else if is_executable_named(&path, stem) {
                out.push(path);
            }
        }
    }
    let mut out = Vec::new();
    walk(root, stem, depth, &mut out);
    out
}

fn family_label(path: &str) -> &'static str {
    match BrowserFamily::of(path) {
        BrowserFamily::Chromium => "chromium",
        BrowserFamily::Firefox => "firefox",
        BrowserFamily::Camoufox => "camoufox",
    }
}

/// Return the profile directory for this app and family, creating it.
///
/// A profile written by the pre-family layout (`external\<id>\`, shared by
/// Chrome and Camoufox) is moved into its family folder once, so splitting the
/// folders does not look like a silent logout to anyone already using it.
fn prepare_external_profile(app_id: &str, family: BrowserFamily) -> (PathBuf, Option<String>) {
    let dir = paths::external_profile(app_id, family.dir_name());
    // Create first: adopting a pre-family profile moves entries *into* `dir`, so
    // it has to exist. `existed` is captured before that, because a folder this
    // call just created must not count as "already migrated".
    let existed = dir.exists();
    paths::ensure(dir.clone());
    let note = if existed {
        None
    } else {
        let legacy = paths::legacy_external_profile(app_id);
        adopt_legacy_profile(&legacy, &dir, family.is_gecko())
    };
    (dir, note)
}

/// Move a pre-family profile into `dir`.
///
/// Only a folder that actually holds *this* family's format is adopted: a
/// Chromium `Local State` must never be moved into `gecko\`, and vice versa.
/// Anything unrecognised is left where it is rather than guessed at, because a
/// wrong move destroys the profile it was meant to save.
///
/// `dir` is a child of `legacy`, so `legacy` cannot simply be renamed into
/// place. It is parked beside itself first, then its entries are moved down one
/// level. Entries that cannot be moved (a browser holding a lock) stay in the
/// parked folder rather than being deleted with the rest.
fn adopt_legacy_profile(legacy: &Path, dir: &Path, want_gecko: bool) -> Option<String> {
    if !legacy.is_dir() {
        return None;
    }
    // Gecko writes `prefs.js` at the profile root; Chromium writes `Local State`.
    let looks_gecko = legacy.join("prefs.js").is_file();
    let looks_chromium = legacy.join("Local State").is_file();
    if want_gecko != looks_gecko || want_gecko == looks_chromium {
        return None;
    }
    let parent = legacy.parent()?;
    let name = legacy.file_name()?.to_string_lossy().into_owned();
    let parked = parent.join(format!("{name}.migrating"));
    if parked.exists() || std::fs::rename(legacy, &parked).is_err() {
        return None;
    }
    // `dir` lived inside `legacy`, so the rename above carried it away. Recreate
    // it and move the old entries down one level, skipping the family folder
    // itself (it is where everything is going).
    let skip = dir.file_name().map(|n| n.to_owned());
    paths::ensure(dir.to_path_buf());
    let mut moved = 0usize;
    let mut stuck = 0usize;
    if let Ok(entries) = std::fs::read_dir(&parked) {
        for entry in entries.flatten() {
            if skip.as_deref() == Some(entry.file_name().as_os_str()) {
                continue;
            }
            if std::fs::rename(entry.path(), dir.join(entry.file_name())).is_ok() {
                moved += 1;
            } else {
                stuck += 1;
            }
        }
    }
    if stuck > 0 {
        // Put the leftovers back where they were so nothing is lost, and leave
        // the new folder in place: the app keeps working, with a partial move
        // the user can see rather than a silent deletion.
        paths::ensure(legacy.to_path_buf());
        for entry in std::fs::read_dir(&parked).into_iter().flatten().flatten() {
            if skip.as_deref() == Some(entry.file_name().as_os_str()) {
                continue;
            }
            let _ = std::fs::rename(entry.path(), legacy.join(entry.file_name()));
        }
        let _ = std::fs::remove_dir_all(&parked);
        return Some(format!(
            "Kept the existing profile in {}: {} item(s) could not be moved while the \
             browser was running.",
            legacy.display(),
            stuck
        ));
    }
    let _ = std::fs::remove_dir_all(&parked);
    (moved > 0).then(|| {
        format!(
            "Existing {} profile moved into the {} folder, so this app keeps its session.",
            if want_gecko { "Firefox" } else { "Chromium" },
            if want_gecko { "gecko" } else { "chromium" }
        )
    })
}

/// Launch an external-browser tab with the proxy its settings resolve to.
/// When no browser is chosen and a proxy IS resolved, we auto-detect the first
/// installed Chromium-family browser so proxy flags can actually be applied
/// (OS default browser cannot receive proxy flags). Falls back to the OS
/// default browser when nothing detected or no proxy is needed.
#[tauri::command]
pub fn open_external(
    app: App,
    app_handle: tauri::AppHandle,
) -> Result<LaunchReport, String> {
    // Only meaningful for external engine; embedded tabs use the webview path.
    if app.engine != Engine::External {
        return Err("not an external app".to_string());
    }

    // Resolved in exactly one place (`settings::resolve`) so an external browser
    // and an embedded tab can never disagree about an app's proxy.
    let mut notes: Vec<String> = Vec::new();
    let resolved = {
        use tauri::Manager;
        let state: tauri::State<crate::config::AppState> = app_handle.state();
        let cfg = state.config.lock().map_err(|e| e.to_string())?;
        let index = cfg.apps.iter().position(|a| a.id == app.id).unwrap_or(0);
        crate::settings::resolve(&cfg.settings, &app, index)
    };
    let proxy = match resolved {
        Resolved::Direct => None,
        Resolved::Use(proxy) => Some(proxy),
        // Not a silent fallback: tunnelled traffic going out in the clear is a
        // privacy failure, so the launch still happens but says what went wrong.
        Resolved::PoolUnavailable(reason) => {
            notes.push(format!(
                "The proxy pool could not supply a proxy ({reason}), so this window opened \
                 directly. Fix the pool in Settings, or set this app to \"no proxy\"."
            ));
            None
        }
    };

    let browser_path = match (&app.external_browser_path, &proxy) {
        (None, Some(_)) => match first_chromium_browser() {
            Some(p) => p,
            // Documented limit: the OS default browser accepts no flags, so the
            // proxy cannot be applied. Say so instead of silently ignoring it.
            None => {
                open_with_default(&app.url)?;
                return Ok(LaunchReport {
                    browser: "system default".to_string(),
                    family: "unknown",
                    profile: String::new(),
                    proxy_applied: false,
                    seed_applied: false,
                    notes: vec![
                        "Opened in the system default browser, which accepts no flags: the \
                         proxy was not applied."
                            .to_string(),
                    ],
                });
            }
        },
        (None, None) => {
            open_with_default(&app.url)?;
            return Ok(LaunchReport {
                browser: "system default".to_string(),
                family: "unknown",
                profile: String::new(),
                proxy_applied: false,
                seed_applied: false,
                notes,
            });
        }
        (Some(p), _) => p.clone(),
    };

    let family = BrowserFamily::of(&browser_path);

    // Per-app, per-family profile. This must NOT live in the temp directory: a
    // stealth browser keeps its fingerprint seed, cookies and history here, and
    // a temp cleanup would silently log the user out.
    let (dir, adopted) = prepare_external_profile(&app.id, family);

    let proxy_uri = proxy.as_ref().map(resolve_proxy_uri);
    let mut plan = plan(
        &app,
        family,
        Path::new(&browser_path),
        &dir,
        proxy_uri.as_deref(),
    );
    if let Some(note) = adopted {
        plan.notes.push(note);
    }
    plan.notes.append(&mut notes);

    if let Some(user_js) = &plan.user_js {
        write_user_js(&dir, user_js)?;
    }

    let mut cmd = std::process::Command::new(&plan.program);
    cmd.args(&plan.args);
    for (key, value) in &plan.env {
        cmd.env(key, value);
    }
    cmd.arg(&app.url);
    cmd.spawn()
        .map_err(|e| format!("failed to launch {}: {e}", plan.program.display()))?;

    Ok(LaunchReport {
        browser: plan
            .program
            .file_name()
            .map(|f| f.to_string_lossy().into_owned())
            .unwrap_or_else(|| plan.program.display().to_string()),
        family: family_label(&browser_path),
        profile: dir.display().to_string(),
        proxy_applied: proxy_uri.is_some(),
        seed_applied: app
            .fingerprint
            .as_deref()
            .map(str::trim)
            .is_some_and(|s| !s.is_empty())
            && !family.is_gecko(),
        notes: plan.notes,
    })
}

/// Resolve a configured proxy to the URI the browser should use.
///
/// An authenticated proxy is rewritten to a local forwarder that injects the
/// credentials, because neither Chromium nor Firefox can take them inline.
///
/// The scheme is normalised first: WebView2 and wry only parse `http` and
/// `socks5`, so an `https://` proxy would otherwise fail to parse and leave the
/// app with no proxy at all — the failure mode that looks like "proxy ignored".
pub(crate) fn resolve_proxy_uri(proxy: &crate::config::Proxy) -> String {
    let scheme = proxy.normalized_scheme();
    match (&proxy.username, &proxy.password) {
        (Some(u), Some(p)) if !u.is_empty() => {
            match crate::proxy_auth::get_local_port_for(scheme, &proxy.host, proxy.port, u, p) {
                Ok(local) => format!("{scheme}://127.0.0.1:{local}"),
                // Falling back to the direct URI keeps the app usable; the
                // proxy will simply reject the unauthenticated connection.
                Err(_) => format!("{scheme}://{}:{}", proxy.host, proxy.port),
            }
        }
        _ => format!("{scheme}://{}:{}", proxy.host, proxy.port),
    }
}

/// First installed Chromium-family browser (proxy-capable), priority order.
fn first_chromium_browser() -> Option<String> {
    let detected = detect_browsers();
    for name in ["brave", "chrome", "edge", "vivaldi", "opera", "cloakbrowser"] {
        if let Some(b) = detected.iter().find(|d| d.name == name) {
            return Some(b.path.clone());
        }
    }
    None
}

fn open_with_default(url: &str) -> Result<(), String> {
    #[cfg(target_os = "windows")]
    {
        use std::os::windows::process::CommandExt;
        std::process::Command::new("cmd")
            .args(["/C", "start", "", url])
            .creation_flags(0x0800_0000) // CREATE_NO_WINDOW
            .spawn()
            .map_err(|e| e.to_string())?;
        Ok(())
    }
    #[cfg(target_os = "macos")]
    {
        std::process::Command::new("open")
            .arg(url)
            .spawn()
            .map_err(|e| e.to_string())?;
        Ok(())
    }
    #[cfg(all(not(target_os = "windows"), not(target_os = "macos")))]
    {
        std::process::Command::new("xdg-open")
            .arg(url)
            .spawn()
            .map_err(|e| e.to_string())?;
        Ok(())
    }
}

/// Whether a URL uses a scheme we are willing to hand to the OS.
///
/// Split out from [`open_in_default_browser`] so the rule can be tested without
/// launching anything: a test that actually opened the URL would pop a browser
/// window on every `cargo test`.
pub(crate) fn is_web_scheme(url: &str) -> bool {
    // Only real web and mail schemes are forwarded. Anything else is a URL the
    // page invented, and passing it to the shell would hand `cmd /C start` a
    // string it might interpret as an option or a command.
    const ALLOWED: [&str; 5] = ["http://", "https://", "mailto:", "tel:", "ftp://"];
    let lower = url.trim().to_ascii_lowercase();
    ALLOWED.iter().any(|prefix| lower.starts_with(prefix))
}

/// Hand a URL to the OS default browser.
///
/// Public because the tab's new-window handler needs it: a link with
/// `target="_blank"` inside an embedded app can be sent here instead of being
/// followed in the app's own tab. No proxy, no profile and no session travel with
/// it — the default browser is a different cookie jar, which is exactly the
/// trade-off the user picks when they choose "External" for that app.
pub fn open_in_default_browser(url: &str) -> Result<(), String> {
    if !is_web_scheme(url) {
        return Err(format!("refusing to open a non-web link: {url}"));
    }
    open_with_default(url.trim())
}

